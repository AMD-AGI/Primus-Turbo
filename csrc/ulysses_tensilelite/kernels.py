"""Generate the TensileLite kernel libraries of the TENSILELITE Ulysses backend into ``primus_turbo/lib/ulysses_tl``.

One library per hop, from the logic in ``logic/<hop>/``, with ``TensileCreateLibrary`` of the TensileLite toolkit
(``tools/build_tensilelite.sh``): ``primus_turbo/lib/ulysses_tl/<hop>/library/<arch>/``, next to a copy of the
manifest the runtime checks them against. The manifest pins every
generated file's sha256 for its ``rocm_libraries_commit`` and ``toolchain``: a library is installed only when all of
its files have the pinned bytes, and one that does not (stale, or generated by another toolchain) is removed.
``generate()`` makes ``TensileCreateLibrary`` output byte-identical across runs, directories and machines, which is
what makes the pins work.

    python csrc/ulysses_tensilelite/kernels.py [--toolkit DIR] [--check] [--force] [--update-pins] [--strict]

setup.py runs ``build()`` when it builds the backend. Standard library only: setup.py loads it by path.
"""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Optional

HERE = Path(__file__).resolve().parent
MANIFEST_PATH = HERE / "manifest.json"
LOGIC_DIR = HERE / "logic"
OUT_DIR = HERE.parents[1] / "primus_turbo" / "lib" / "ulysses_tl"
HOPS = ("fwd_gemm_a2a", "fwd_a2a_gemm", "bwd_gemm_a2a", "bwd_a2a_gemm")
TAG = "[ulysses_tl]"


def load_manifest() -> dict:
    return json.loads(MANIFEST_PATH.read_text())


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _files(root: Path) -> dict:
    """{path relative to ``root``: sha256} of every file under ``root``."""
    root = Path(root)
    return {p.relative_to(root).as_posix(): _sha256(p) for p in sorted(root.rglob("*")) if p.is_file()}


def unavailable_reason(out_dir: Path = OUT_DIR, hops=HOPS) -> Optional[str]:
    """None when every hop in ``hops`` is in ``out_dir`` with exactly its pinned files, else why not."""
    pins = load_manifest()["libraries"]
    for hop in hops:
        if hop not in pins:
            return f"{hop} has no pinned library"
        hop_dir = Path(out_dir) / hop
        if not hop_dir.is_dir():
            return f"{hop} is not generated"
        if _files(hop_dir) != pins[hop]:
            return f"{hop} is not the pinned library"
    return None


def compiler_version(rocm_path: Optional[str]) -> str:
    cxx = (
        shutil.which("amdclang++", path=str(Path(rocm_path) / "bin"))
        if rocm_path
        else shutil.which("amdclang++")
    )
    if cxx is None:
        return "?"
    try:
        r = subprocess.run([cxx, "--version"], capture_output=True, text=True, errors="replace", check=True)
    except (OSError, subprocess.SubprocessError):
        return "?"
    return r.stdout.splitlines()[0].strip() if r.stdout else "?"


def generate(toolkit: Path, hop: str, out: Path, rocm_path: Optional[str] = None, jobs: int = 0) -> None:
    """``TensileCreateLibrary`` of one hop's logic into ``out`` (``out/library/<arch>/``)."""
    toolkit = Path(toolkit)
    arch = load_manifest()["arch"]
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join(
        p for p in (str(toolkit / "python"), str(toolkit / "tensilelite"), env.get("PYTHONPATH")) if p
    )
    if rocm_path:
        env["ROCM_PATH"] = str(rocm_path)
    # The helper kernels (Kernels.so-*.hsaco) are compiled from a temporary path, and clang's default HIP
    # compilation-unit id hashes that path, so their bytes differ on every compile. TensileLite's per-user helper
    # cache would hide that on one machine only.
    env["CCC_OVERRIDE_OPTIONS"] = "+-fuse-cuid=none"
    env["TENSILE_DISABLE_HELPER_CACHE"] = "1"
    cmd = [
        sys.executable,
        str(toolkit / "tensilelite" / "bin" / "TensileCreateLibrary"),
        "--enable-gemm-a2a-fusion",
        "--code-object-version=V5",
        "--library-format=msgpack",
        f"--architecture={arch}",
        "--no-enumerate",
        f"-j{jobs or os.cpu_count() or 1}",
        str(LOGIC_DIR / hop),
        str(out),
        "HIP",
    ]
    # cwd: TensileCreateLibrary leaves a MatchTable.yaml in its working directory
    with tempfile.TemporaryDirectory() as cwd:
        r = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        raise RuntimeError(
            f"{hop}: {' '.join(cmd)} failed ({r.returncode}):\n{(r.stdout + r.stderr)[-4000:]}"
        )


def build(
    toolkit: Path,
    out_dir: Path = OUT_DIR,
    rocm_path: Optional[str] = None,
    force: bool = False,
    update_pins: bool = False,
    log=print,
) -> bool:
    """Generate every hop into ``out_dir``; True when every hop there has its pinned files.

    Hops already pinned are kept (unless ``force``). A new library is installed only when its files are the pinned
    ones (``update_pins`` writes the new sha256 into the manifest instead), and an unpinned one left in ``out_dir``
    is removed. Without the manifest's ``toolchain`` (it cannot reproduce the pins) nothing is generated. Never
    raises for a hop, so it cannot fail an install."""
    out_dir = Path(out_dir)
    manifest = load_manifest()
    todo = [h for h in HOPS if force or update_pins or unavailable_reason(out_dir, [h]) is not None]
    if todo:
        version = compiler_version(rocm_path)
        if version != manifest["toolchain"]:
            log(
                f"{TAG} WARNING: the compiler is {version!r}, not the pinned toolchain; kernel libraries not generated"
            )
            todo = []
    for hop in todo:
        with tempfile.TemporaryDirectory() as tmp:
            staged = Path(tmp) / hop
            try:
                generate(toolkit, hop, staged, rocm_path)
                got = _files(staged)
                if update_pins:
                    manifest["libraries"][hop] = got
                elif got != manifest["libraries"].get(hop):
                    raise RuntimeError("the generated files are not the pinned ones")
                shutil.rmtree(out_dir / hop, ignore_errors=True)
                out_dir.mkdir(parents=True, exist_ok=True)
                shutil.move(str(staged), str(out_dir / hop))
                log(f"{TAG} generated {hop} ({len(got)} files)")
            except Exception as e:  # noqa: BLE001 -- a library that does not generate must not fail the install
                log(f"{TAG} WARNING: {hop} not generated: {type(e).__name__}: {e}")
    if update_pins:
        MANIFEST_PATH.write_text(json.dumps(manifest, indent=2) + "\n")
        log(f"{TAG} pins written to {MANIFEST_PATH}")
    ok = True
    for hop in HOPS:
        if unavailable_reason(out_dir, [hop]) is not None:
            ok = False
            if (out_dir / hop).exists():
                shutil.rmtree(out_dir / hop)
                log(f"{TAG} removed {hop}: not the pinned library")
    if out_dir.is_dir():
        # the runtime checks the installed libraries against this copy (csrc/ is not installed)
        shutil.copyfile(MANIFEST_PATH, out_dir / MANIFEST_PATH.name)
    if ok and not todo:
        log(f"{TAG} kernel libraries up to date in {out_dir}")
    return ok


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--toolkit", default=os.environ.get("TENSILELITE_HOME", "/opt/tensilelite"))
    ap.add_argument("--rocm-path", default=os.environ.get("ROCM_PATH"))
    ap.add_argument("--out-dir", default=str(OUT_DIR))
    ap.add_argument("--check", action="store_true", help="only verify the generated libraries")
    ap.add_argument("--force", action="store_true", help="regenerate libraries that are already pinned")
    ap.add_argument(
        "--update-pins", action="store_true", help="regenerate every hop and pin what it generates"
    )
    ap.add_argument("--strict", action="store_true", help="exit 1 unless every library is pinned")
    a = ap.parse_args(argv)
    if a.check:
        reason = unavailable_reason(Path(a.out_dir))
        print(reason or "ok")
        return 1 if reason else 0
    ok = build(Path(a.toolkit), Path(a.out_dir), a.rocm_path, a.force, a.update_pins)
    return 0 if ok or not a.strict else 1


if __name__ == "__main__":
    sys.exit(main())
